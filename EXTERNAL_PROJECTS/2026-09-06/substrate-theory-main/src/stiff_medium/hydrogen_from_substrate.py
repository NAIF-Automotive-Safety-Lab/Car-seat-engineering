# §4: Compare to Rydberg expectations
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class HydrogenComparisonRow:
    """One row of the substrate-vs-Rydberg comparison.

    Attributes:
        state:           Label, e.g. '1s', '2s', '2p'.
        E_substrate_eV:  Energy from substrate solver [eV].
        E_rydberg_eV:    Energy from -R_∞/n² formula [eV].
        diff_eV:         |E_sub - E_rydberg|.
        rel_error:       diff / |E_rydberg|.
        passes:          True if rel_error < 0.01 (1% tolerance).
    """
    state: str
    E_substrate_eV: float
    E_rydberg_eV: float
    diff_eV: float
    rel_error: float
    passes: bool


def compare_substrate_vs_rydberg(
    result: HydrogenSubstrateResult,
    states: list[tuple[str, int]] | None = None,
) -> list[HydrogenComparisonRow]:
    """Compare substrate-derived energies to standard Rydberg formula.

    The Rydberg formula gives E_n = -13.6056 / n² eV.  This is what we
    EXPECT to see if the substrate's V(r) actually behaves like -α ℏc/r
    AND m_e is the right kink mass.

    Args:
        result:  Output of solve_hydrogen_substrate.
        states:  List of (label, n) pairs.  Defaults to ['1s', '2s', '3s', '4s']
                 with n = 1, 2, 3, 4.

    Returns:
        List of HydrogenComparisonRow.
    """
    if states is None:
        states = [("1s", 1), ("2s", 2), ("3s", 3), ("4s", 4)]

    rows: list[HydrogenComparisonRow] = []
    for i, (label, n) in enumerate(states):
        if i >= len(result.E_n_eV):
            break
        E_sub = result.E_n_eV[i]
        E_ryd = -RYDBERG_EV / n**2
        diff = abs(E_sub - E_ryd)
        rel = diff / abs(E_ryd)
        rows.append(
            HydrogenComparisonRow(
                state=label,
                E_substrate_eV=E_sub,
                E_rydberg_eV=E_ryd,
                diff_eV=diff,
                rel_error=rel,
                passes=(rel < 0.01),
            )
        )
    return rows


