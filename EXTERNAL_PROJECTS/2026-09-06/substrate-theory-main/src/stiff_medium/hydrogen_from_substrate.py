# ---------------------------------------------------------------------------
# §1: Proton substrate charge density ρ_p(r)
# ---------------------------------------------------------------------------


def proton_charge_density_substrate(
    r_m: np.ndarray,
    sigma_GeV2: float = SIGMA_QCD_GEV2,
    m_eff_GeV: float | None = None,
) -> np.ndarray:
    """3D radial charge density of the proton from the Y-junction wavefunction.

    Substrate construction
    ----------------------
    The proton is a Y-junction of three quark kinks bound in V_QCD = σ r.
    Each quark's wavefunction in the Y-junction is approximately Gaussian:

        ψ_q(r) = (α_q/π)^(3/4) exp(-α_q r²/2)

    with α_q determined variationally (proton_radius_v3.solve_variational_quark_wavefunction).
    The proton's TOTAL charge density at distance r from the center
    (when the three quark distributions overlap and the +2/3, +2/3, -1/3
    charges sum to +1) is:

        ρ_p(r) = (2/3) |ψ_u(r)|² + (2/3) |ψ_u(r)|² + (-1/3) |ψ_d(r)|²

    Assuming all three quarks have the same wavefunction (an approximation
    that's exact to leading order in the constituent quark mass), this
    reduces to:

        ρ_p(r) = (2/3 + 2/3 - 1/3) |ψ_q(r)|² = |ψ_q(r)|²

    normalized so ∫ ρ_p(r) 4π r² dr = +1 (total charge in units of e).

    Args:
        r_m: Radial distances [metres].  Array of grid points.
        sigma_GeV2: String tension [GeV²].  Default: σ_QCD = 0.180.
        m_eff_GeV: Constituent kink mass [GeV].  Default: √σ.

    Returns:
        Charge density ρ_p(r) at each r_m, in units of e/m³ (charges per
        cubic metre).  Sign: positive (proton is +1 charged).  Norm:
        ∫ ρ_p 4π r² dr = +1 (when integrated over all space).
    """
    var = solve_variational_quark_wavefunction(sigma_GeV2, m_eff_GeV)
    # alpha_min has units GeV²; convert to m⁻² via (ℏc)² in GeV²·m².
    hbarc_GeV_m = HBARC_GEV_FM * 1e-15  # GeV·m
    alpha_q_inv_m2 = var.alpha_min_GeV2 / hbarc_GeV_m**2  # m⁻²

    # |ψ(r)|² = (α/π)^(3/2) exp(-α r²); single-quark normalised in 3D.
    # Total charge: u + u + d-bar = +2/3 + 2/3 - 1/3 = +1.
    # Identical wavefunctions ⇒ ρ_total = |ψ|² (already normalised to 1).
    pre = (alpha_q_inv_m2 / math.pi) ** 1.5  # m⁻³
    rho = pre * np.exp(-alpha_q_inv_m2 * r_m**2)
    return rho


def proton_charge_density_finite_size_lookup(
    r_m: np.ndarray,
    R_p_m: float = R_PROTON_FM * 1e-15,
) -> np.ndarray:
    """Proton charge density: simple Gaussian fit with the substrate radius.

    For sanity checks: use a simple Gaussian profile of width R_p (the
    substrate-derived proton radius) so that ⟨r²⟩^(1/2) = R_p, with the
    correct +1 total charge.

        ρ_p(r) = (1/(π R_p² (3/2))^(3/2)) exp(-3 r² / (2 R_p²))

    so that ∫ ρ 4π r² dr = 1 and ⟨r²⟩ = R_p².  This is a simpler model
    than the variational Y-junction wavefunction but gives essentially
    identical results for r >> R_p.

    Args:
        r_m: Radial distances [metres].
        R_p_m: Proton charge radius [metres].

    Returns:
        ρ_p(r) [m⁻³], normalised so ∫ 4πr² ρ dr = 1.
    """
    # ⟨r²⟩ for a Gaussian (β/π)^(3/2) exp(-β r²) is 3/(2β).  Set ⟨r²⟩ = R_p²:
    # β = 3/(2 R_p²).
    beta = 1.5 / R_p_m**2
    pre = (beta / math.pi) ** 1.5
    return pre * np.exp(-beta * r_m**2)


# ---------------------------------------------------------------------------
# §2: Substrate Coulomb potential V_sub(r)
# ---------------------------------------------------------------------------


def substrate_coulomb_potential(
    r_m: np.ndarray,
    rho_p_m_inv3: np.ndarray,
    alpha_sub: float = ALPHA_SUB,
) -> np.ndarray:
    """Solve ∇² V = -4π α ℏc · ρ_p for V_sub(r) given ρ_p(r).

    Substrate physics (NOT plugged-in Coulomb law)
    ----------------------------------------------
    The substrate's Möbius half-flux U(1) bundle (spec §18.10) carries a
    gauge connection A whose holonomy gives charge quantisation.  The
    static, spherically symmetric limit of the bundle's gauge field
    equation is:

        ∇² A_0 = -4π α ℏc · ρ                        (Gauss's law on bundle)

    where ρ is the charge density and α appears as the bundle's natural
    coupling constant (see photon_renormalization.py for the substrate's
    derivation of α from one-loop bundle physics).

    The 3D Laplacian Green's function gives:

        V_sub(r) = -4π α ℏc · ∫ ρ_p(r') G(r,r') d³r'    where G = -1/(4π|r-r'|)

    For spherically symmetric ρ_p, this reduces to the standard shell
    integral form (Newton's shell theorem applied to electrostatics):

        V_sub(r) = -α ℏc / r · Q_enc(r)
                 - α ℏc · ∫_r^∞ 4π r' ρ_p(r') dr'

    where Q_enc(r) = ∫_0^r 4π r'² ρ_p(r') dr' is the enclosed charge.

    For r → ∞: Q_enc → 1 and the second integral → 0, so V → -α ℏc / r
    (the standard Coulomb potential of a +1 charge).  This is the FORM
    that the substrate produces — not a plug-in.

    For r → 0: ρ_p is finite (proton is not a point), so V → finite
    constant -α ℏc · ⟨1/r⟩_p ~ -α ℏc / R_p.

    Args:
        r_m: Radial grid [metres], must be monotonically increasing.
        rho_p_m_inv3: Proton charge density on the grid [m⁻³].
        alpha_sub: Substrate fine-structure constant.

    Returns:
        V_sub(r) on the grid [Joules].  Negative (attractive) for an
        electron in a proton's field.
    """
    # Convert α ℏc to SI Joule·metres:
    # α ℏc = (1/137) × 1.0546e-34 [J·s] × 3e8 [m/s]
    HBAR_SI = 1.054571817e-34  # J·s
    C_SI = 2.99792458e8        # m/s
    e_SI = 1.602176634e-19     # C (used only for unit consistency)

    alpha_hbarc = alpha_sub * HBAR_SI * C_SI  # J·m  — this is α ℏc in SI

    # Compute the enclosed charge Q_enc(r) and the outer integral ∫_r^∞ ρ r' dr'.
    # Discretization: trapezoidal cumulative integrals.
    n = len(r_m)
    if n < 2:
        raise ValueError("Need at least 2 grid points for radial integration.")

    # Differential element 4π r² ρ for the enclosed charge integral
    integrand_enc = 4.0 * math.pi * r_m**2 * rho_p_m_inv3
    # Cumulative trapezoidal integration: Q_enc[i] = ∫_0^{r_i} integrand dr
    dr = np.diff(r_m)
    avg_enc = 0.5 * (integrand_enc[:-1] + integrand_enc[1:])
    Q_enc = np.concatenate([[0.0], np.cumsum(avg_enc * dr)])

    # Outer integral: ∫_r^∞ 4π r' ρ(r') dr' (the "potential at center
    # contribution from outer charges").
    integrand_out = 4.0 * math.pi * r_m * rho_p_m_inv3
    avg_out = 0.5 * (integrand_out[:-1] + integrand_out[1:])
    cum_out = np.concatenate([[0.0], np.cumsum(avg_out * dr)])
    total_out = cum_out[-1]
    outer_integral = total_out - cum_out  # = ∫_{r_i}^∞ 4π r' ρ dr'

    # V_sub(r) = -α ℏc [Q_enc(r)/r + outer_integral(r)]
    # Avoid division by zero at the smallest r:
    r_safe = np.where(r_m > 0, r_m, np.inf)
    V_sub = -alpha_hbarc * (Q_enc / r_safe + outer_integral)

    return V_sub


def substrate_potential_pointlike(r_m: np.ndarray, alpha_sub: float = ALPHA_SUB) -> np.ndarray:
    """Pure 1/r form for cross-check (the limit of substrate V at r >> R_p).

    Returns V(r) = -α ℏc / r in Joules.  Identical to the substrate
    potential at r >> R_p; deviates inside the proton.

    Args:
        r_m: Radial grid [metres].
        alpha_sub: Substrate α.

    Returns:
        V(r) [Joules].
    """
    HBAR_SI = 1.054571817e-34
    C_SI = 2.99792458e8
    alpha_hbarc = alpha_sub * HBAR_SI * C_SI
    r_safe = np.where(r_m > 0, r_m, np.inf)
    return -alpha_hbarc / r_safe


