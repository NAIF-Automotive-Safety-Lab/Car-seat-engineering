"""Hydrogen ground state from substrate dynamics — no Rydberg formula reuse.

Methodological intent
---------------------
The question being answered: given only substrate primitives, does the
substrate framework actually PRODUCE the hydrogen orbital structure, or
have we been smuggling in QM via Rydberg-formula shortcuts?

This module solves the hydrogen atom from the bottom up:

  1. Build the proton's substrate charge distribution ρ_p(r) directly
     from the Y-junction wavefunction (proton_radius_v3.py): three
     constituent kinks with charge density given by their wavefunction
     spread inside the linear V = σ r confining potential.

  2. Solve the substrate's Maxwell-like equation
         ∇² V_sub(r) = -4π α ℏc · ρ_p(r) / e
     for the potential generated by ρ_p(r).  This is the static Coulomb
     limit of the substrate's U(1) gauge field on the Möbius bundle:
     the long-range part of a moving Möbius half-flux is exactly the
     Coulomb field (Gauss's law follows from the bundle's flux
     conservation; the 1/r in 3D follows from the bundle propagator
     being the 3D Laplacian Green's function).

  3. Solve the radial Schrödinger equation
         [-ℏ²/(2 m_e) (1/r²) d/dr (r² d/dr) + V_sub(r) + ℏ²ℓ(ℓ+1)/(2m_e r²)] ψ = E ψ
     for the electron-kink in the proton's substrate field.  Use:
         m_e = 0.5109989461 MeV (substrate kink mass at electron Compton
         scale ξ_e = 3.86×10⁻¹³ m — see lepton_masses_from_K.py)

  4. Extract:
         - E_0 (1s)              — should be ≈ -13.606 eV
         - E_1 (2s, 2p)          — should be ≈ -3.401 eV
         - 1s-2s splitting       — should be ≈ 10.20 eV
         - ⟨r⟩ in 1s             — should be ≈ 1.5 a₀ ≈ 7.94×10⁻¹¹ m
         - ψ(0)                  — finite if ρ_p has a soft core, divergent if point

What is INHERITED (substrate-numerical inputs):
---------------------------------------------
  - α_substrate ≈ 1/137.036 — from photon_renormalization.py / alpha_derivation.py.
    The model produces Z_photon < 1 ratio that lands near 137 but doesn't
    derive 1/α to better than O(1) without the multi-loop computation
    flagged in spec §18.48.7 item 1.
  - m_e = 0.511 MeV — kink mass at the electron Compton scale.

What is DERIVED here:
---------------------
  - The FORM V(r) ∝ 1/r at large r — comes from the 3D bundle Maxwell
    Green's function (∇² in 3D has 1/(4πr) Green's function).
  - The DEVIATION from 1/r at small r — comes from the non-pointlike
    proton charge distribution ρ_p(r) computed from the Y-junction
    wavefunction.
  - The ENTIRE bound-state spectrum E_n, ψ_n(r) — comes from solving
    the radial Schrödinger problem with this substrate-derived V(r).
    Nothing in this step uses the Rydberg formula.

Honest physics statements
-------------------------
  - At r >> R_p ≈ 0.84 fm, V_sub(r) → -α ℏc / r exactly (Coulomb limit
    of a +1 net charge).
  - At r ~ R_p, V_sub is finite and smooth (the proton is not a delta).
  - At r >> a₀ ≈ 5.3×10⁻¹¹ m, the electron sees an effectively point
    charge — the difference between V_sub and -α ℏc/r is invisible at
    the bound-state scale.
  - Therefore the bound state energy SHOULD reproduce -13.606 eV to
    within the ratio (R_p/a₀)² ≈ 2×10⁻¹⁰ accuracy, IF α and m_e are
    correct.
  - Any deviation we see signals either: (a) numerical discretization
    error, (b) the proton-finite-size correction (real, ~10⁻⁹ eV in
    1s), or (c) wrong substrate values for α or m_e.

References
----------
    spec §18.45 (encompassing Lagrangian)
    spec §18.20 (EM as substrate wave)
    spec §18.10 (Möbius bundle, half-flux holonomy)
    proton_radius_v3.py    (Y-junction wavefunction → ρ_p)
    photon_renormalization.py (substrate α via Z_photon)
    lepton_masses_from_K.py   (substrate m_e at ξ_e)
"""

