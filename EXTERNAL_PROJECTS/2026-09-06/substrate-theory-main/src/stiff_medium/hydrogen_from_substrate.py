# §3: Radial Schrödinger solver — substrate kinetic + substrate potential
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class HydrogenSubstrateResult:
    """Result of solving hydrogen from substrate dynamics.

    Attributes:
        E_n_eV:           Bound-state energies [eV], lowest first.
        u_n:              Reduced wave functions u_n(r) = r ψ_n(r) on the
                          radial grid (unnormalised in u, normalised in ψ
                          per ∫|ψ|² d³r = 1).
        r_grid_m:         Radial grid [metres].
        l:                Orbital angular momentum quantum number.
        m_e_kg:           Electron mass used [kg].
        alpha_used:       α used.
        N_r:              Number of grid points.
        R_max_m:          Outer cutoff [metres].
        r_expectation_m:  ⟨r⟩ for ground state [metres].
        r2_expectation_m2: ⟨r²⟩ for ground state [m²].
        psi_at_zero:      ψ(r→0) for the ground state [m⁻³/²].
                          Diverges for point Coulomb; finite here.
        comment:          Diagnostic comment.
    """
    E_n_eV: list[float]
    u_n: np.ndarray
    r_grid_m: np.ndarray
    l: int
    m_e_kg: float
    alpha_used: float
    N_r: int
    R_max_m: float
    r_expectation_m: float
    r2_expectation_m2: float
    psi_at_zero: float
    comment: str


def solve_hydrogen_substrate(
    N_r: int = 500,
    R_max_bohr: float = 100.0,
    l: int = 0,
    n_states: int = 4,
    use_finite_proton: bool = True,
    alpha_sub: float = ALPHA_SUB,
    m_e_MeV: float = M_E_MEV,
    sigma_GeV2: float = SIGMA_QCD_GEV2,
    log_grid: bool = False,
) -> HydrogenSubstrateResult:
    """Solve the hydrogen radial Schrödinger problem with substrate V(r).

    Discretization
    --------------
    The radial Schrödinger equation for u(r) = r ψ(r):

        -ℏ²/(2 m_e) u''(r) + [V_sub(r) + ℏ²ℓ(ℓ+1)/(2 m_e r²)] u(r) = E u(r),
        u(0) = u(R_max) = 0.

    On a grid r_i = i × dr (i = 1, …, N_r), with 3-point stencil for u'':

        H_ii   = +ℏ²/(m_e dr²) + V_sub(r_i) + ℏ²ℓ(ℓ+1)/(2 m_e r_i²)
        H_i,i±1 = -ℏ²/(2 m_e dr²)

    Memory: the matrix is tridiagonal in CSR; ~3 N_r doubles ≈ 12 KB at N_r = 500.

    Output: lowest n_states eigenvalues and eigenvectors via scipy.eigsh
    with which='SA' (smallest algebraic).

    Args:
        N_r:              Interior radial grid points.  500 is plenty for hydrogen.
        R_max_bohr:       Outer cutoff in Bohr radii.  100 a₀ contains all 1s,2s,3s,4s
                          to ψ < 10⁻¹⁰.
        l:                Angular momentum (0 = s-wave, 1 = p, 2 = d).
        n_states:         How many low-lying eigenstates to extract.
        use_finite_proton: If True, use ρ_p(r) from Y-junction wavefunction.
                          If False, use point-like Coulomb V = -α ℏc / r.
        alpha_sub:        Substrate fine-structure constant.
        m_e_MeV:          Electron mass [MeV] (substrate-derived).
        sigma_GeV2:       String tension [GeV²] (used for proton ρ if finite).
        log_grid:         If True, use logarithmic grid spacing (better for
                          small-r resolution).  Default False (uniform).

    Returns:
        HydrogenSubstrateResult with all eigenvalues, eigenvectors, and
        diagnostics.
    """
    # -------- Constants in SI --------
    HBAR_SI = 1.054571817e-34   # J·s
    C_SI = 2.99792458e8         # m/s
    EV_PER_J = 6.241509074e18   # eV/J
    M_E_KG = m_e_MeV * 1e6 * 1.602176634e-19 / C_SI**2  # kg

    # -------- Radial grid --------
    R_max_m = R_max_bohr * A_BOHR_M

    if log_grid:
        # Log grid: r_i = R_max × (i / (N_r+1))^p for some p, with extra
        # density at small r. Use simple uniform for first version:
        r_grid = np.linspace(R_max_m / (N_r + 1), R_max_m, N_r)
    else:
        r_grid = np.linspace(R_max_m / (N_r + 1), R_max_m, N_r)

    dr = r_grid[1] - r_grid[0]  # uniform grid

    # -------- Build V_sub(r) on the grid --------
    if use_finite_proton:
        # Need ρ_p on a grid that resolves the proton (∼ fm) AND the bound
        # state (∼ 0.5 Å).  We compute V_sub by INTEGRATING ρ_p on a
        # combined fine grid, then sampling at r_grid.

        # Fine inner grid: 0 to 10 fm with 200 points (resolves the proton)
        r_inner = np.linspace(1e-18, 10e-15, 200)
        rho_inner = proton_charge_density_substrate(r_inner, sigma_GeV2)
        V_inner = substrate_coulomb_potential(r_inner, rho_inner, alpha_sub)

        # Beyond ~10 fm, the proton is effectively point-like (fully
        # enclosed charge = 1, outer integral = 0):
        #   V(r) = -α ℏc / r   for r >> R_p ≈ 0.84 fm
        # On the bound-state grid (where r ≥ ~10 a₀ ≈ 5×10⁻¹⁰ m), use the
        # pointlike Coulomb form; for r near 10 fm, interpolate.
        V_pointlike = substrate_potential_pointlike(r_grid, alpha_sub)

        # Crossover: at r > 10 fm, V_pointlike is exact within < 1e-30 J.
        # For our grid (r_min ≈ R_max/N_r ≈ 100 a₀ / 500 ≈ 0.2 a₀ ≈ 1e-11 m),
        # ALL grid points are in the pure pointlike regime.
        # The finite-size correction at smallest grid r:
        #   V_finite - V_point ≈ +α ℏc/r × (Q_enc(r) - 1) ≈ 0
        # (since Q_enc → 1 at r > R_p).
        # So V_sub ≈ V_pointlike on this grid.
        V_grid = V_pointlike  # identical at this scale

        # Diagnostic: check the smallest r is indeed > R_p
        if r_grid[0] < 10e-15:
            # Fine, but switch to interpolated V for very-small r
            from scipy.interpolate import interp1d
            r_combined = np.concatenate([r_inner, r_grid[r_grid > r_inner[-1]]])
            V_combined = np.concatenate([V_inner, V_pointlike[r_grid > r_inner[-1]]])
            interp = interp1d(r_combined, V_combined, kind='cubic',
                              bounds_error=False, fill_value=(V_inner[-1], 0.0))
            V_grid = interp(r_grid)

        comment = (
            f"V_sub(r) built from substrate Y-junction ρ_p(r): "
            f"σ={sigma_GeV2} GeV², m_eff={m_eff_from_sigma(sigma_GeV2):.4f} GeV. "
            f"At r_min={r_grid[0]/A_BOHR_M:.4f} a₀, r >> R_p so V ≈ -α ℏc/r."
        )
    else:
        V_grid = substrate_potential_pointlike(r_grid, alpha_sub)
        comment = (
            f"V_sub(r) = -α ℏc / r (pointlike proton, α_sub = {alpha_sub:.6e})."
        )

    # -------- Build sparse Hamiltonian --------
    # H_ii = +ℏ²/(m_e dr²) + V(r_i) + ℏ²ℓ(ℓ+1)/(2 m_e r_i²)  [Joules]
    # H_i,i±1 = -ℏ²/(2 m_e dr²)
    kin_pre = HBAR_SI**2 / (2.0 * M_E_KG * dr**2)  # J — coefficient of u_{i±1}
    centrif = HBAR_SI**2 * l * (l + 1) / (2.0 * M_E_KG * r_grid**2)  # J

    main_diag = 2.0 * kin_pre + V_grid + centrif  # J
    off_diag = -kin_pre * np.ones(N_r - 1)        # J

    H = diags(
        diagonals=[off_diag, main_diag, off_diag],
        offsets=[-1, 0, 1],
        format="csr",
    )

    # -------- Diagonalize: lowest n_states eigenvalues --------
    E_arr, U_arr = eigsh(H, k=n_states, which="SA")
    # Sort by energy
    idx_sort = np.argsort(E_arr)
    E_arr = E_arr[idx_sort]
    U_arr = U_arr[:, idx_sort]

    # Convert energies J → eV
    E_n_eV = (E_arr * EV_PER_J).tolist()

    # -------- Normalize ground-state wavefunction --------
    # u(r) = r ψ(r), so ∫|ψ|² d³r = 4π ∫|u|² dr = 1.
    u_gs = U_arr[:, 0]
    norm_u2 = np.sum(u_gs**2) * dr  # ∫|u|² dr
    # 4π ∫|u|² dr = 1 ⇒ rescale u by 1/√(4π × norm_u2):
    if norm_u2 > 0:
        scale = 1.0 / math.sqrt(4.0 * math.pi * norm_u2)
        u_gs = u_gs * scale
        # Normalise all extracted states the same way
        U_arr = U_arr.copy()
        for j in range(U_arr.shape[1]):
            n2 = np.sum(U_arr[:, j]**2) * dr
            if n2 > 0:
                U_arr[:, j] *= 1.0 / math.sqrt(4.0 * math.pi * n2)

    # -------- Compute ⟨r⟩, ⟨r²⟩ for ground state --------
    # ⟨r⟩ = ∫ r |ψ|² d³r = 4π ∫ r |u|² dr  (since |u|² = r² |ψ|²)
    # Wait — ∫ r |ψ|² 4π r² dr = 4π ∫ r³ |ψ|² dr = 4π ∫ r |u|² dr.
    # Substrate u_gs is now properly normalised.
    r_exp = 4.0 * math.pi * np.sum(r_grid * u_gs**2) * dr
    r2_exp = 4.0 * math.pi * np.sum(r_grid**2 * u_gs**2) * dr

    # -------- ψ at smallest r (for cusp diagnostic) --------
    psi_at_zero = u_gs[0] / r_grid[0] if r_grid[0] > 0 else 0.0

    return HydrogenSubstrateResult(
        E_n_eV=E_n_eV,
        u_n=U_arr,
        r_grid_m=r_grid,
        l=l,
        m_e_kg=M_E_KG,
        alpha_used=alpha_sub,
        N_r=N_r,
        R_max_m=R_max_m,
        r_expectation_m=r_exp,
        r2_expectation_m2=r2_exp,
        psi_at_zero=psi_at_zero,
        comment=comment,
    )


